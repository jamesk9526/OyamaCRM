import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { _electron as electron } from 'playwright';
const profile = await mkdtemp(path.join(os.tmpdir(),'oyama-bridge-v2-qa-'));
await writeFile(path.join(profile,'oyama-bridge-config.json'),JSON.stringify({bridgeAutostart:false,bridgeEnabled:false,startHidden:false,bridgeModel:'qwen3.5:9b',bridgeThinkingModel:'qwen3.5:9b',bridgeCudaDevice:'1'}));
const evidence='docs/status/audit-artifacts/2026-11-01-bridge-pairing';
await mkdir(evidence,{recursive:true});
const packaged=process.env.BRIDGE_QA_EXECUTABLE;
const app=await electron.launch({executablePath:packaged||path.resolve('OyamaBridgeDesktopServer/node_modules/electron/dist/electron.exe'),args:packaged?[]:[path.resolve('OyamaBridgeDesktopServer')],env:{...process.env,OYAMA_BRIDGE_DATA_DIR:profile}});
const errors=[];
try {
 const page=await app.firstWindow();page.on('pageerror',error=>errors.push(error.message));
 await page.waitForLoadState('domcontentloaded');
 await page.getByRole('heading',{name:'Oyama Bridge',exact:true}).waitFor();
 await page.waitForFunction(()=>document.getElementById('titleModelValue').textContent.includes('qwen3.5'),{timeout:45000});
 await page.screenshot({path:`${evidence}/bridge-dashboard.png`,animations:'disabled'});
 const save=await page.evaluate(()=>window.oyamaBridge.saveImprovement({rating:'down',reason:'incorrect',note:'Synthetic QA report; no donor data.'}));
 assert.equal(save.ok,true);
 await page.getByRole('button',{name:'Open command sidebar',exact:true}).click();
 await page.locator('[data-tab-target="improvements"]').first().click();
 await page.getByRole('heading',{name:'Improvements log',exact:true}).waitFor();
 assert.ok((await page.locator('[data-tab-page="improvements"]').boundingBox()).width>600);
 await page.getByText('Synthetic QA report; no donor data.',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Sync pending reports'}).click();
 await page.getByRole('status').filter({hasText:'Reports remain queued locally'}).waitFor();
 const state=await page.evaluate(()=>window.oyamaBridge.getImprovements());assert.equal(state.pending,1);
 await page.screenshot({path:`${evidence}/bridge-improvements.png`,animations:'disabled'});
 await page.setViewportSize({width:1100,height:800});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await app.evaluate(({shell})=>{shell.openExternal=async url=>{globalThis.__qaConnectionUrl=url;};});
 await page.locator('[data-tab-target="pairing"]:visible').first().click();
 await page.getByRole('heading',{name:'Connect your CRM',exact:true}).waitFor();
 await page.locator('#connectCrmSite').fill('https://crm.example.invalid');
 await page.locator('#connectCrmEndpoint').fill('http://127.0.0.1:43110');
 await page.getByRole('button',{name:'Sign in and connect CRM',exact:true}).click();
 await page.locator('#connectCrmStatus').filter({hasText:'CRM opened'}).waitFor();
 const handoff=await app.evaluate(()=>globalThis.__qaConnectionUrl);
 assert.ok(new URL(handoff).hash.startsWith('#bridgePair='));
 assert.equal(new URL(handoff).search,'');
 const cfg=await page.evaluate(()=>window.oyamaBridge.getConfig());
 assert.equal(cfg.bridgeCudaDevice,'1');
 await page.screenshot({path:`${evidence}/bridge-connect.png`,animations:'disabled'});
 await page.getByText('Advanced: import an older CRM connection key',{exact:true}).click();
 await page.locator('#pairingInput').fill(JSON.stringify({version:1,kind:'oyama.bridge.pairing',expiresAt:new Date(Date.now()+60000).toISOString(),bridgeConfig:{bridgeAutostart:false,bridgeApiKey:'qa-test-key-123456',bridgeModel:'qwen3.5:9b',bridgeThinkingModel:'qwen3.5:9b',bridgeCudaDevice:'auto'}}));
 await page.getByRole('button',{name:'Apply Pairing',exact:true}).click();
 await page.waitForFunction(async()=> (await window.oyamaBridge.getConfig()).bridgeApiKey==='qa-test-key-123456');
 const afterImport=await page.evaluate(()=>window.oyamaBridge.getConfig());assert.equal(afterImport.bridgeCudaDevice,'1','legacy CRM export must not reset the desktop GPU');
 assert.deepEqual(errors,[]);
 await writeFile(`${evidence}/bridge-checks.json`,JSON.stringify({packaged:!!packaged,errors,checks:['renderer startup','light dashboard capture','feedback persisted','unconnected sync preserves report','improvements capture','1100px overflow','fragment handoff opens normal CRM sign-in','GPU preserved across legacy import']},null,2));
} finally { await app.close(); }
